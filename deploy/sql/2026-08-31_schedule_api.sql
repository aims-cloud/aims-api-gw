-- 스케줄 트리거 API — 스케줄 정의·실행 이력 (feat/scheduler-core 단계 3)
-- VM PostgreSQL 은 ddl-auto: update 라 Hibernate 가 자동 반영하지만,
-- 스키마를 의도대로 고정하기 위해 스크립트로도 남긴다.
--   psql -U aims -d aims -f 2026-08-31_schedule_api.sql
--
-- 주의 1: 기존 테이블에 더하는 컬럼은 모두 nullable 이다. 행이 이미 있는 테이블에
--         NOT NULL 컬럼을 추가하면 ddl-auto=update 가 실패한다.
-- 주의 2: 시각 컬럼은 전부 UTC(timestamptz)다. 화면 표출 변환은 프런트가 한다.
--         다만 schedules.cron_expression 은 시간대를 담을 수 없어
--         **한국 시간(Asia/Seoul, UTC+9) 입력으로 가정**해 해석한다.
--         배포 VM 은 OS·DB 모두 Etc/UTC 이므로 이 가정이 없으면 화면에서 "02:00" 으로
--         만든 스케줄이 한국 시간 오전 11시에 실행된다.
--         근거와 변환 규칙은 CronSupport 클래스 주석 참고.

-- ── 스케줄 정의 ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS schedules (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id                VARCHAR(50)  NOT NULL UNIQUE,   -- 사용자가 정하는 업무 키(불변)
    name                       VARCHAR(100) NOT NULL,
    resource_type              VARCHAR(20),                    -- NULL = VM 으로 해석
    cron_expression            VARCHAR(120) NOT NULL,          -- Quartz 표기 원문(KST 기준 해석)
    auto_run                   BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled                    BOOLEAN      NOT NULL DEFAULT TRUE,
    description                VARCHAR(300),

    -- 명세 확장 (화면에 없음, 전부 선택)
    engine                     VARCHAR(30),
    policy_id                  BIGINT,
    max_power_budget_watts     DOUBLE PRECISION,
    max_temperature_celsius    DOUBLE PRECISION,

    -- 최근 실행 스냅샷 (목록이 이력을 조인하지 않게 비정규화)
    last_run_status            VARCHAR(20),
    last_run_at                TIMESTAMPTZ,
    last_run_finished_at       TIMESTAMPTZ,
    last_run_message           VARCHAR(500),
    next_run_at                TIMESTAMPTZ,

    created_by                 VARCHAR(100),
    created_by_name            VARCHAR(100),
    updated_by                 VARCHAR(100),
    updated_by_name            VARCHAR(100),
    created_at                 TIMESTAMPTZ,
    updated_at                 TIMESTAMPTZ
);

-- 러너가 10초마다 "실행할 때가 된 스케줄"을 찾는다.
CREATE INDEX IF NOT EXISTS idx_schedules_next_run_at ON schedules (next_run_at);

-- ── 실행 이력 ────────────────────────────────────────────────
-- 자동 실행이 대상 0건으로 끝나면 행을 만들지 않는다. 5분 주기 스케줄 하나가
-- 90일이면 "대상 없음" 행만 25,920개가 되기 때문이다. 수동 실행은 항상 기록한다.
CREATE TABLE IF NOT EXISTS schedule_runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id    BIGINT      NOT NULL,        -- schedules.id (외래키를 두지 않는다)
    schedule_key   VARCHAR(50),                 -- 표시용 업무 키 사본
    trigger_type   VARCHAR(20) NOT NULL,        -- AUTO | MANUAL
    status         VARCHAR(20) NOT NULL,        -- RUNNING | COMPLETED | FAILED
    started_at     TIMESTAMPTZ,
    finished_at    TIMESTAMPTZ,
    message        VARCHAR(500),
    target_count   INTEGER     NOT NULL DEFAULT 0,
    success_count  INTEGER     NOT NULL DEFAULT 0,
    failed_count   INTEGER     NOT NULL DEFAULT 0,
    truncated      BOOLEAN     NOT NULL DEFAULT FALSE,
    engine_id      VARCHAR(30),
    policy_name    VARCHAR(100),
    triggered_by   VARCHAR(100)                 -- 자동 실행은 SYSTEM
);

CREATE INDEX IF NOT EXISTS idx_schedule_runs_schedule_id
    ON schedule_runs (schedule_id, started_at);

-- ── 기존 테이블 확장 ─────────────────────────────────────────
-- 배치에 실패한 워크로드도 다음 실행에서 다시 시도한다. 자원이 영영 모자란 워크로드가
-- 매 실행마다 재시도되어 이력을 채우지 않도록 누적 횟수를 세고 상한(기본 5)에서 제외한다.
ALTER TABLE workloads ADD COLUMN IF NOT EXISTS retry_count INTEGER;

-- 실행 1건과 워크로드별 배치 결정을 연결한다.
-- 외래키를 두지 않으므로 실행 이력을 지울 때 DB 가 정리해 주지 않는다.
-- 코드에서 schedule_run_id 를 NULL 로 만든 뒤 이력을 지운다(결정 내용은 보존).
ALTER TABLE scheduling_history ADD COLUMN IF NOT EXISTS schedule_run_id BIGINT;
ALTER TABLE scheduling_history ADD COLUMN IF NOT EXISTS success         BOOLEAN;

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 제약을 만든다.
-- 자동 생성되지 않은 환경을 위해 같은 제약을 명시한다.
-- ※ 값을 추가할 때는 DROP 후 새 값 목록으로 다시 만들어야 한다
--   (ddl-auto=update 는 기존 CHECK 제약을 수정하지 않는다 — 개발순서.md 부록 A)
ALTER TABLE schedules DROP CONSTRAINT IF EXISTS schedules_resource_type_check;
ALTER TABLE schedules ADD CONSTRAINT schedules_resource_type_check
    CHECK (resource_type IS NULL OR resource_type IN ('VM', 'GPU', 'NPU', 'CONTAINER'));

ALTER TABLE schedules DROP CONSTRAINT IF EXISTS schedules_last_run_status_check;
ALTER TABLE schedules ADD CONSTRAINT schedules_last_run_status_check
    CHECK (last_run_status IS NULL OR last_run_status IN ('RUNNING', 'COMPLETED', 'FAILED'));

ALTER TABLE schedule_runs DROP CONSTRAINT IF EXISTS schedule_runs_trigger_type_check;
ALTER TABLE schedule_runs ADD CONSTRAINT schedule_runs_trigger_type_check
    CHECK (trigger_type IN ('AUTO', 'MANUAL'));

ALTER TABLE schedule_runs DROP CONSTRAINT IF EXISTS schedule_runs_status_check;
ALTER TABLE schedule_runs ADD CONSTRAINT schedule_runs_status_check
    CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED'));

