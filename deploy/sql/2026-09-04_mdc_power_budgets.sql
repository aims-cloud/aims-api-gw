-- MDC 전력 예산 원장 — MDC 한 곳이 쓸 수 있는 전력 총량(W) (feat/mdc-power-budget, 단계 21)
-- 지금까지 전력 상한은 노드 한 대 기준뿐이었다. 그런데 MDC 는 컨테이너·랙 단위 수전 용량이 곧 상한이라,
-- 노드 8대가 각자 정격 아래여도 합계가 계약 용량을 넘으면 실제로는 올릴 수 없다. 이 표가 그 총량을 담는다.
-- 단계 20 의 node_power_specs 가 "한 대의 정격"이라면 이 표는 "한 곳의 총량"이다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 덮어써 Hibernate 가 자동 생성한다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남기고, 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -f 2026-09-04_mdc_power_budgets.sql
--
-- 예산에는 크기 상한을 두지 않는다(노드 전력 사양과 같은 판단). 실데이터가 없는 지금 상한은 추측이라
-- 정당한 규모를 막을 수 있다 — MDC 한 곳이 수십 kW 에서 수백 kW 까지 간다. 서비스는 "0 보다 큰 유한한 값"만 검사한다.

CREATE TABLE IF NOT EXISTS mdc_power_budgets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mdc_id           VARCHAR(100)     NOT NULL,   -- Prometheus mdc_id 라벨과 같은 문자열 (라벨 없는 노드는 unknown)
    budget_watts     DOUBLE PRECISION NOT NULL,   -- 전력 예산(W), 0 초과·유한
    source           VARCHAR(20)      NOT NULL,   -- MANUAL | SPEC_SHEET | MEASURED (MEASURED 는 예약)
    description      VARCHAR(300),

    created_by       VARCHAR(100),
    created_by_name  VARCHAR(100),
    updated_by       VARCHAR(100),
    updated_by_name  VARCHAR(100),
    created_at       TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT uq_mdc_power_budgets_mdc UNIQUE (mdc_id)
);

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 제약을 만든다. 값을 추가할 때는 DROP 후 다시 만든다
-- (ddl-auto=update 는 기존 CHECK 를 수정하지 않는다).
ALTER TABLE mdc_power_budgets DROP CONSTRAINT IF EXISTS mdc_power_budgets_source_check;
ALTER TABLE mdc_power_budgets ADD CONSTRAINT mdc_power_budgets_source_check
    CHECK (source IN ('MANUAL', 'SPEC_SHEET', 'MEASURED'));

