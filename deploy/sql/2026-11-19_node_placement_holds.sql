-- 노드 배치 중지 원장 — 운영자가 새 배치를 받지 않게 한 노드 (feat/scheduler-node-placement-hold)
-- 행이 있는 노드는 다음 배치부터 제약 평가의 맨 앞에서 빠진다(제외 사유 NODE_PLACEMENT_HOLD). 지우면 다시 후보가 된다.
-- 이미 배치되거나 실행 중인 워크로드는 건드리지 않는다. 자산 원장의 점검 상태와는 별개다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 덮어써 Hibernate 가 자동 생성한다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남기고, 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -f 2026-11-19_node_placement_holds.sql

CREATE TABLE IF NOT EXISTS node_placement_holds (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id          VARCHAR(100)     NOT NULL,   -- /nodes 의 nodeId 와 같은 문자열 (대소문자 구분 · 등록 뒤 바꾸지 않음)
    reason           VARCHAR(300),                -- 중지 사유 (배치 이력의 제외 사유 문장에 실림)

    created_by       VARCHAR(100),
    created_by_name  VARCHAR(100),
    updated_by       VARCHAR(100),
    updated_by_name  VARCHAR(100),
    created_at       TIMESTAMPTZ,                 -- 등록 시각 = 배치 중지 시작 시각
    updated_at       TIMESTAMPTZ,

    CONSTRAINT uq_node_placement_holds_node UNIQUE (node_id)
);

