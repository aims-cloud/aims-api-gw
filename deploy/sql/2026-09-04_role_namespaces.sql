-- 역할(Role) ↔ CB-Tumblebug Namespace 매핑 테이블 (feat/monitoring)
-- 자원 탐색기 가상머신 가지의 역할별 접근 범위 원장 (docs/06 자원 탐색기 트리 설계 §9.1)
-- 물리 자원은 role_assets(Role → Asset.id), 가상머신은 role_namespaces(Role → Tumblebug nsId) 로 연결한다.
-- Tumblebug Label 에는 권한 정보를 저장하지 않는다. 역할:Namespace 는 N:M.
-- VM PostgreSQL은 ddl-auto: validate 이므로 배포 전 수동 실행 필요:
--   psql -U aims -d aims -f 2026-09-04_role_namespaces.sql

CREATE TABLE IF NOT EXISTS role_namespaces (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id    BIGINT NOT NULL REFERENCES roles (id),
    ns_id      VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_role_namespaces_role_ns UNIQUE (role_id, ns_id)
);

-- 자원 탐색기 조회 경로: 역할 → Namespace 목록
CREATE INDEX IF NOT EXISTS idx_role_namespaces_role_id ON role_namespaces (role_id);
