-- 알람 발생 이력 원장 재정의 (feat/alarm) — docs/09 알람 설계 A.5.3 · B.4.7 · C.2
-- 초안 alarm_history(rule_id FK, instance, metric_value, severity 문자열)를 같은 이름으로 재정의한다.
-- 기존 행은 규칙 4종의 자동 생성 데이터라 보존하지 않고 DROP 한다(필요하면 DROP 전에 alarm_history_legacy 로 RENAME).
-- 정책·자원·기준·관측값은 발생 시점 스냅샷이며 policy_id 는 조인용 약한 참조(FK 없음).
-- VM PostgreSQL은 ddl-auto: validate 이므로 새 백엔드 기동 전 수동 실행 필요:
--   sudo -u postgres psql -d aims -v ON_ERROR_STOP=1 -f 2026-09-08_alarm_history_redefine.sql
--   sudo -u postgres psql -d aims -c "ALTER TABLE alarm_history OWNER TO aims;"   -- 백엔드 접속 계정과 맞춘다

DROP TABLE IF EXISTS alarm_history;

CREATE TABLE alarm_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          VARCHAR(16)  NOT NULL,               -- POLICY | SYSTEM | EXTERNAL | EVENT
    policy_id       BIGINT,                              -- alarm_policies.id (약한 참조)
    policy_name     VARCHAR(100),                        -- 발생 시점 스냅샷
    level           VARCHAR(16)  NOT NULL,               -- INFO | WARNING | CRITICAL
    resource_type   VARCHAR(20),                         -- node | vm | gpu
    resource_id     VARCHAR(200),                        -- assets.id 또는 TB:{ns}/{infra}/{node}
    resource_name   VARCHAR(200),
    role_name       VARCHAR(50),                         -- 역할 스코프. SYSTEM 알람은 NULL(전체 공개)
    area_id         VARCHAR(120),                        -- 자원 영역: MDC 는 mdcId, Namespace 는 TB:{nsId} (역할 패널 areaId 와 동일)
    area_kind       VARCHAR(16),                         -- MDC | NAMESPACE
    metric          VARCHAR(50),                         -- 메트릭 카탈로그 코드
    criterion       VARCHAR(200) NOT NULL,               -- 예: "CPU Used > 80%"
    observed_value  DOUBLE PRECISION,
    unit            VARCHAR(10),
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at     TIMESTAMP WITH TIME ZONE,
    status          VARCHAR(16)  NOT NULL,               -- OPEN | ACKNOWLEDGED | RESOLVED
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    acknowledged_by VARCHAR(64),
    ack_content     VARCHAR(1000),
    fingerprint     VARCHAR(64),                         -- 외부 알람 멱등 키
    inhibited       BOOLEAN      NOT NULL DEFAULT FALSE, -- 상위 알람에 눌려 전송 억제
    labels_json     TEXT,                                -- 외부 알람 원문 라벨
    delivery_count  INTEGER      NOT NULL DEFAULT 0,     -- 전송 이력 수(비정규화)
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alarm_history_occurred_at    ON alarm_history (occurred_at);
CREATE INDEX IF NOT EXISTS idx_alarm_history_role_occurred  ON alarm_history (role_name, occurred_at);
CREATE INDEX IF NOT EXISTS idx_alarm_history_resource       ON alarm_history (resource_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_alarm_history_policy         ON alarm_history (policy_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_alarm_history_status         ON alarm_history (status);
CREATE INDEX IF NOT EXISTS idx_alarm_history_fingerprint    ON alarm_history (fingerprint);
