-- 스케줄러 기반 테이블 — workloads · scheduling_policies · scheduling_history (fix/scheduler-schema-baseline, 단계 23)
--
-- 이 세 표는 스케줄러가 가장 먼저 만든 표인데도 지금까지 CREATE 가 한 줄도 없었다.
-- ALTER 만 있었다(2026-08-31_scheduler_extension.sql · 2026-08-31_schedule_api.sql).
-- 드러나지 않은 이유는 배포 VM 이 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 리포 기본값을 덮어써
-- Hibernate 가 표를 자동으로 만들어 왔기 때문이다.
--
--   → 리포 기본값은 validate 다(application.yml). 그 환경변수 한 줄이 없는 새 DB 에서는
--     "missing table [workloads]" 로 **앱 전체가 기동하지 않는다.** 스케줄러만 죽는 것이 아니다.
--
-- 실행:
--   psql -U aims -d aims -v ON_ERROR_STOP=1 -f 2026-09-04_scheduler_base_tables.sql
--   (ON_ERROR_STOP 을 붙인다 — psql 기본값은 문장이 실패해도 계속 진행이라, CHECK 하나가 실패한 것을
--    모른 채 뒤 문장이 다 돌아 버린다)
--
-- 실행 순서 주의 — 새 DB 에 스크립트를 몰아서 돌린다면 **이 파일을 2026-08-31_* 보다 먼저** 실행해야 한다
--   (파일명은 작성 날짜이지 실행 순서가 아니다. 전체 순서는 deploy/sql/README.md 참고).
--   그 두 파일이 여기 있는 표에 ALTER 를 걸기 때문에, 파일명(날짜) 순으로 돌리면 대상이 없어 실패한다.
--   이미 표가 있는 DB(배포 VM)에서는 IF NOT EXISTS 라 아무 일도 하지 않는다 — 언제 돌려도 안전하다.
--
-- 컬럼 구성은 엔티티를 기준으로 적었다. 나중에 ALTER 로 더해진 컬럼(resource_type·data_mdc_id·retry_count·
-- schedule_run_id·success 등)도 여기에 이미 포함돼 있어, 새 DB 는 이 파일 하나로 최종 형태가 된다.
-- 뒤이어 2026-08-31_* 을 돌려도 전부 IF NOT EXISTS / DROP 후 재생성이라 부작용이 없다.

-- ── 워크로드 ─────────────────────────────────────────────────
-- required_disk_gb 는 단계 12(디스크 요구량 제약)에서 엔티티에 들어왔지만 DDL 이 한 줄도 없었다.
-- VM 은 ddl-auto=update 가 채워 줘서 드러나지 않았을 뿐이다. 여기서 함께 고정한다.
CREATE TABLE IF NOT EXISTS workloads (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(100)     NOT NULL,
    description             VARCHAR(300),

    -- 자원 요구량
    required_cpu            INTEGER          NOT NULL DEFAULT 0,
    required_memory_mb      INTEGER          NOT NULL DEFAULT 0,
    required_gpu            INTEGER          NOT NULL DEFAULT 0,
    required_disk_gb        INTEGER          NOT NULL DEFAULT 0,
    resource_type           VARCHAR(20),                        -- NULL = VM 으로 해석

    -- 제약 조건
    preferred_mdc_id        VARCHAR(50),
    data_mdc_id             VARCHAR(50),                        -- 데이터가 있는 MDC — 링크 비용 계산에 쓴다
    max_power_budget_watts  DOUBLE PRECISION,
    max_temperature_celsius DOUBLE PRECISION,
    priority                VARCHAR(20)      NOT NULL DEFAULT 'NORMAL',

    -- 배치 결과
    assigned_mdc_id         VARCHAR(50),
    assigned_node_id        VARCHAR(100),
    status                  VARCHAR(20)      NOT NULL DEFAULT 'PENDING',
    scheduling_score        DOUBLE PRECISION,
    scheduling_reason       VARCHAR(500),
    retry_count             INTEGER,                            -- NULL = 0 으로 해석

    created_at              TIMESTAMPTZ,
    scheduled_at            TIMESTAMPTZ
);

-- ── 배치 정책 ────────────────────────────────────────────────
-- 활성 정책의 유일성(종류별 1개 + 공통 1개)은 애플리케이션이 보장한다(단계 13).
-- 부분 유니크 인덱스는 2026-08-31_scheduler_extension.sql 에 선택 실행으로 남아 있다.
CREATE TABLE IF NOT EXISTS scheduling_policies (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        VARCHAR(100)     NOT NULL UNIQUE,
    description                 VARCHAR(300),
    resource_type               VARCHAR(20),                    -- NULL = 종류를 가리지 않는 공통 정책
    default_engine              VARCHAR(30),                    -- NULL = weighted
    warning_temperature_celsius DOUBLE PRECISION,               -- NULL = 설정 기본값

    -- 스코어링 가중치 (합계 1.0)
    cpu_weight                  DOUBLE PRECISION NOT NULL DEFAULT 0.25,
    memory_weight               DOUBLE PRECISION NOT NULL DEFAULT 0.25,
    power_weight                DOUBLE PRECISION NOT NULL DEFAULT 0.20,
    temperature_weight          DOUBLE PRECISION NOT NULL DEFAULT 0.15,
    network_weight              DOUBLE PRECISION NOT NULL DEFAULT 0.15,

    -- 제약 임계치
    max_cpu_usage_percent       DOUBLE PRECISION NOT NULL DEFAULT 80.0,
    max_memory_usage_percent    DOUBLE PRECISION NOT NULL DEFAULT 85.0,
    max_temperature_celsius     DOUBLE PRECISION NOT NULL DEFAULT 75.0,
    max_power_usage_percent     DOUBLE PRECISION NOT NULL DEFAULT 90.0,

    power_aware_enabled         BOOLEAN          NOT NULL DEFAULT TRUE,
    temperature_aware_enabled   BOOLEAN          NOT NULL DEFAULT TRUE,
    affinity_enabled            BOOLEAN          NOT NULL DEFAULT FALSE,
    active                      BOOLEAN          NOT NULL DEFAULT TRUE,

    created_at                  TIMESTAMPTZ
);

-- ── 배치 결정 이력 ───────────────────────────────────────────
-- 이 표는 **지워지지 않는다.** 연구 근거 자료라 실행 이력(schedule_runs) 정리 때도 함께 지우지 않고
-- schedule_run_id 만 NULL 로 끊는다. 그래서 단조 증가하며, 인덱스가 필수다(아래).
-- schedule_run_id 에 외래키를 두지 않은 것도 같은 이유다 — DB 가 연쇄 삭제하면 근거가 사라진다.
CREATE TABLE IF NOT EXISTS scheduling_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id       BIGINT,
    workload_name     VARCHAR(100),
    selected_mdc_id   VARCHAR(50),
    selected_node_id  VARCHAR(100),
    final_score       DOUBLE PRECISION NOT NULL DEFAULT 0,

    -- 차원별 점수
    cpu_score         DOUBLE PRECISION NOT NULL DEFAULT 0,
    memory_score      DOUBLE PRECISION NOT NULL DEFAULT 0,
    power_score       DOUBLE PRECISION NOT NULL DEFAULT 0,
    temperature_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    network_score     DOUBLE PRECISION NOT NULL DEFAULT 0,

    -- 결정 시점의 노드 상태
    node_cpu_usage    DOUBLE PRECISION NOT NULL DEFAULT 0,
    node_memory_usage DOUBLE PRECISION NOT NULL DEFAULT 0,
    node_power_watts  DOUBLE PRECISION NOT NULL DEFAULT 0,
    node_temperature  DOUBLE PRECISION NOT NULL DEFAULT 0,

    candidate_count   INTEGER          NOT NULL DEFAULT 0,
    reason            VARCHAR(500),
    engine_name       VARCHAR(50),
    policy_name       VARCHAR(100),
    schedule_run_id   BIGINT,                                   -- 단건 스케줄링 API 로 만든 이력은 NULL
    success           BOOLEAN,                                  -- NULL 은 성공으로 본다(기존 행)

    created_at        TIMESTAMPTZ
);

-- ── 기존 DB 보정 ─────────────────────────────────────────────
-- 위 CREATE 는 표가 하나라도 있으면 **표 전체가 no-op** 이라 컬럼 단위로는 아무것도 고치지 못한다.
-- required_disk_gb 는 단계 12 에서 엔티티에 들어왔는데 그때 ALTER 를 남기지 않았다. 지금까지 ddl-auto=update 가
-- 채워 줘서 드러나지 않았을 뿐, update 를 쓰지 않는 기존 DB 에는 이 컬럼이 없다. 여기서 함께 보정한다.
-- 이미 있으면 아무 일도 하지 않는다. 기존 행에는 DEFAULT 0 이 즉시 채워진다(PostgreSQL 11+ 는 표를 다시 쓰지 않는다).
ALTER TABLE workloads ADD COLUMN IF NOT EXISTS required_disk_gb INTEGER NOT NULL DEFAULT 0;

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 를 만든다. 자동 생성되지 않은 환경을 위해 명시한다.
-- ※ 값을 추가할 때는 DROP 후 다시 만든다 — ddl-auto=update 는 기존 CHECK 를 수정하지 않는다.
ALTER TABLE workloads DROP CONSTRAINT IF EXISTS workloads_status_check;
ALTER TABLE workloads ADD CONSTRAINT workloads_status_check
    CHECK (status IN ('PENDING', 'SCHEDULED', 'RUNNING', 'COMPLETED', 'FAILED'));

ALTER TABLE workloads DROP CONSTRAINT IF EXISTS workloads_priority_check;
ALTER TABLE workloads ADD CONSTRAINT workloads_priority_check
    CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'CRITICAL'));

-- resource_type CHECK 은 2026-08-31_scheduler_extension.sql 과 같은 이름·같은 값이다.
-- 어느 쪽을 먼저 돌려도 DROP 후 재생성이라 결과가 같다.
ALTER TABLE workloads DROP CONSTRAINT IF EXISTS workloads_resource_type_check;
ALTER TABLE workloads ADD CONSTRAINT workloads_resource_type_check
    CHECK (resource_type IS NULL OR resource_type IN ('VM', 'GPU', 'NPU', 'CONTAINER'));

ALTER TABLE scheduling_policies DROP CONSTRAINT IF EXISTS scheduling_policies_resource_type_check;
ALTER TABLE scheduling_policies ADD CONSTRAINT scheduling_policies_resource_type_check
    CHECK (resource_type IS NULL OR resource_type IN ('VM', 'GPU', 'NPU', 'CONTAINER'));

