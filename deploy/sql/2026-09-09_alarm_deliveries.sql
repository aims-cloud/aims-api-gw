-- 알람 전송 원장 (feat/alarm-notification) — docs/09 알람 설계 A.5.3 · A.5.4
-- alarm_deliveries: 알람 1건 × 전송 대상(개인/조직) × 채널 = 1행, 제목·본문은 발송 시점 스냅샷.
-- alarm_delivery_recipients: 대상을 사용자 단위로 전개한 수신자별 결과(SENDING → SUCCESS | FAILED).
-- history_id·policy_id 는 조인용 약한 참조(FK 없음) — 이력·정책이 지워져도 전송 기록은 남는다.
-- VM PostgreSQL은 ddl-auto: validate 이므로 새 백엔드 기동 전 수동 실행 필요:
--   sudo -u postgres psql -d aims -v ON_ERROR_STOP=1 -f 2026-09-09_alarm_deliveries.sql
--   sudo -u postgres psql -d aims -c "ALTER TABLE alarm_deliveries OWNER TO aims; ALTER TABLE alarm_delivery_recipients OWNER TO aims;"
-- 메일 서버는 /etc/default/aims-cloud-backend 의 SPRING_MAIL_* 환경 변수로 넣는다(deploy/default.env.example 참고).

CREATE TABLE IF NOT EXISTS alarm_deliveries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history_id   BIGINT       NOT NULL,                 -- alarm_history.id (약한 참조)
    policy_id    BIGINT,                                -- alarm_policies.id (약한 참조)
    target_type  VARCHAR(16)  NOT NULL,                 -- INDIVIDUAL | ORGANIZATION
    target_id    VARCHAR(100) NOT NULL,                 -- 개인 = users.id, 조직 = users.organization 문자열
    target_name  VARCHAR(100),                          -- 발송 시점 표시명 (삭제된 사용자는 "(삭제된 사용자)")
    channel      VARCHAR(16)  NOT NULL,                 -- EMAIL | SMS
    subject      VARCHAR(300),
    body         VARCHAR(4000),                         -- 채널별 치환 본문 스냅샷
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_alarm_deliveries_history ON alarm_deliveries (history_id);

CREATE TABLE IF NOT EXISTS alarm_delivery_recipients (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id  BIGINT       NOT NULL REFERENCES alarm_deliveries (id) ON DELETE CASCADE,
    user_id      BIGINT,                                -- users.id (삭제된 사용자는 NULL)
    name         VARCHAR(100),
    address      VARCHAR(200),                          -- EMAIL: 이메일, SMS: 전화번호(users.phone 도입 전 NULL)
    status       VARCHAR(16)  NOT NULL,                 -- SENDING | SUCCESS | FAILED
    attempts     INTEGER      NOT NULL DEFAULT 0,       -- 발송 시도 횟수 (시도 전 FAILED 는 0)
    sent_at      TIMESTAMPTZ,                           -- 마지막 시도 시각
    fail_reason  VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS idx_alarm_delivery_recipients_delivery ON alarm_delivery_recipients (delivery_id);
