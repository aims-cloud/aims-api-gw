-- 단건 배치 입력 (feat/placement-input-capture)
--
-- 단건 배치(POST /api/v1/scheduler/workloads/{workloadId}/schedule) 1회의 입력과 그 결정을 한 행으로 남긴다 —
-- 1세부 실데이터가 들어온 뒤 그 결정을 다시 계산해 보려고. 스케줄 실행은 schedule_run_inputs 가 입력을 남기지만 단건
-- 배치는 입력을 남기지 않았고, 배치 이력(scheduling_history)도 단건 배치는 성공한 결정만 남겼다.
--
-- payload 는 schedule_run_inputs 와 같은 형식의 JSON 문자열이다(format_version 이 형식을 정한다 · 대상 워크로드 1건).
-- 배치 직전의 노드 상태·수집에서 빠진 노드·정책 사본·MDC 예산·링크 원장·냉각 대기·엔진 노브를 담는다.
-- 결정(engine_id · success · selected_node_id)은 엔진이 낸 값이다 — 실행 계층이 받지 않아 실패로 낮춘 결과는
-- 전달 기록(placement_dispatches)에 남는다. 실패한 결정도 남긴다.
--
-- schedule_run_inputs 를 쓰지 않고 표를 따로 둔 까닭: 그 표는 schedule_run_id 가 NOT NULL · 고유라 실행 없는 결정을
-- 담을 수 없다. 실행 이력과 같은 보존 기간(aims.scheduler.run-retention-days)이 지나면 captured_at 기준으로 지운다.
-- 외래키는 두지 않는다(scheduling_history.schedule_run_id 와 같은 관례).
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)이라 Hibernate 가 표를 만들어 준다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남긴다 — 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -v ON_ERROR_STOP=1 -f 2026-10-29_placement_inputs.sql
--
-- 열 크기: 로컬 모의 모드에서 잰 payload 는 5.7KB 안팎이고 노드 수에 따라 늘어난다. 단건 배치 1회마다 한 행이 생긴다.

CREATE TABLE IF NOT EXISTS placement_inputs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id       BIGINT       NOT NULL,   -- workloads.id (외래키 없음)
    format_version    INTEGER      NOT NULL,   -- payload 형식 판(schedule_run_inputs 와 같음)
    captured_at       TIMESTAMPTZ,
    engine_id         VARCHAR(255),            -- 실제로 쓴 엔진
    success           BOOLEAN      NOT NULL,   -- 엔진 결정의 성공 여부
    selected_node_id  VARCHAR(255),            -- 엔진이 고른 노드(실패면 NULL)
    knobs_digest      VARCHAR(12),             -- schedule_runs.snapshot_knobs_digest 와 같은 계산
    input_digest      VARCHAR(12),             -- payload 의 SHA-256 앞 12자
    payload           TEXT
);

CREATE INDEX IF NOT EXISTS ix_placement_inputs_workload ON placement_inputs (workload_id);
CREATE INDEX IF NOT EXISTS ix_placement_inputs_captured ON placement_inputs (captured_at);
