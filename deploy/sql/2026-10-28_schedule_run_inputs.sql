-- 스케줄 실행 입력 (feat/schedule-run-input-capture)
--
-- 스케줄 실행 1회의 배치 입력을 한 행으로 남긴다 — 1세부 실데이터가 들어온 뒤 그 회차를 그대로 다시 돌려 보려고.
-- 실행 이력(schedule_runs)에는 집계와 노브 지문만, 배치 이력(scheduling_history)에는 고른 노드의 값만 남아 회차를
-- 재생할 수 없었다.
--
-- payload 는 JSON 문자열 하나다(format_version 이 형식을 정한다). 배치 루프 직전의 노드 상태(예약 반영 뒤 · 수집 순서)·
-- 수집에서 빠진 노드·대상 워크로드(배치 순서)·정책 사본(스케줄의 온도 상한을 덮어쓴 뒤)·실행 전력 상한·MDC 예산·링크
-- 원장·냉각 대기·엔진 노브(전력·열·네트워크 설정)를 담는다. 루프 안에서 생기는 건너뜀·실행 계층 거부는 배치 이력과
-- 전달 기록에 이미 있으므로 담지 않는다.
--
-- schedule_runs 에 열로 두지 않고 표를 따로 둔 까닭: 실행 이력 목록·상세가 행을 읽을 때 수십 KB 가 넘는 열이 함께 실린다.
-- 실행 이력과 같은 기간만 남는다 — 보존 정리와 스케줄 삭제가 실행 이력을 지울 때 같은 실행 id 로 함께 지운다.
-- 외래키는 두지 않는다(scheduling_history.schedule_run_id 와 같은 관례).
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)이라 Hibernate 가 표를 만들어 준다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남긴다 — 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -v ON_ERROR_STOP=1 -f 2026-10-28_schedule_run_inputs.sql
--
-- 열 크기(추측): 8노드·10워크로드 회차면 payload 가 10KB 안팎이다. PostgreSQL 은 2KB 가 넘는 text 를 압축해 따로 둔다(TOAST).

CREATE TABLE IF NOT EXISTS schedule_run_inputs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_run_id  BIGINT       NOT NULL,   -- schedule_runs.id (외래키 없음)
    format_version   INTEGER      NOT NULL,   -- payload 형식 판
    captured_at      TIMESTAMPTZ,
    knobs_digest     VARCHAR(12),             -- schedule_runs.snapshot_knobs_digest 와 같은 값
    input_digest     VARCHAR(12),             -- payload 의 SHA-256 앞 12자
    payload          TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_schedule_run_inputs_run ON schedule_run_inputs (schedule_run_id);
