-- 역할(Role) ↔ 자산(Asset) 매핑 테이블 (feat/auth)
-- 자원 탐색기의 역할별 자원 스코프 원장 — 자산 하나가 여러 역할에 노출될 수 있는 N:M 구조
-- VM PostgreSQL은 ddl-auto: validate 이므로 배포 전 수동 실행 필요:
--   psql -U aims -d aims -f 2026-09-02_role_assets.sql

CREATE TABLE IF NOT EXISTS role_assets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id    BIGINT NOT NULL REFERENCES roles (id),
    asset_id   BIGINT NOT NULL REFERENCES assets (id),
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_role_assets_role_asset UNIQUE (role_id, asset_id)
);

-- 자원 탐색기 조회 경로: 역할 → 자산 목록 / 자산 → 소속 역할
CREATE INDEX IF NOT EXISTS idx_role_assets_role_id  ON role_assets (role_id);
CREATE INDEX IF NOT EXISTS idx_role_assets_asset_id ON role_assets (asset_id);
