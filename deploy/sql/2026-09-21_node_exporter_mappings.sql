-- 익스포터 대응 원장 — 노드 한 대의 DCGM·IPMI 시리즈 instance (refactor/collector-instance-resolution)
--
-- 프로메테우스의 instance 라벨은 스크레이프 주소 그대로라 익스포터마다 다르다. 배포 서버 실측(2026-09-21):
--   노드 익스포터  localhost:9100
--   DCGM          mdc1-gpu-node1:9400
--   IPMI          ipmi-exporter:9290
-- 수집기는 노드 익스포터의 instance 를 키로 GPU 개수를 찾고 전력·온도를 질의해 왔으므로, 실장비에서는 GPU 개수가
-- 항상 0 이고 전력·온도는 항상 미계측이었다. 이 표는 운영자가 세 값을 잇는 자리다.
--
-- 두 칸 모두 비워 둘 수 있다. 비어 있으면 수집기가 호스트명 일치(포트를 뗀 호스트가 같은 시리즈가 정확히 하나)로
-- 대체하고, 그것도 안 되면 노드 익스포터 instance 를 그대로 쓴다 — 이 표가 생기기 전과 같은 동작이다.
-- 중앙 IPMI 익스포터처럼 호스트명이 다른 형태는 이 표에 적는 길밖에 없다. 단 한 instance 는 한 노드에만 — 같은
-- 시리즈를 두 노드에 넣으면 값이 두 번 세어지므로 API 는 409 로 막고 수집기는 관련 노드를 미계측으로 둔다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)이라 Hibernate 가 표를 만들어 준다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남긴다 — 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -v ON_ERROR_STOP=1 -f 2026-09-21_node_exporter_mappings.sql
--
-- 열거 열이 없다. 열거 열은 처음 만들 때의 값 목록으로 CHECK 가 굳어 값을 더할 때마다 스크립트가 필요하므로,
-- 이 표는 문자열 두 칸만 둔다.

CREATE TABLE IF NOT EXISTS node_exporter_mappings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id          VARCHAR(100)  NOT NULL,   -- 노드 익스포터 instance 라벨 그대로 (예: seoul-01:9100)
    dcgm_instance    VARCHAR(100),             -- 이 노드의 DCGM 시리즈 instance. 비우면 호스트명 일치로 대체
    ipmi_instance    VARCHAR(100),             -- 이 노드의 IPMI 시리즈 instance. 중앙 익스포터면 이 칸이 유일한 길
    description      VARCHAR(300),

    created_by       VARCHAR(100),
    created_by_name  VARCHAR(100),
    updated_by       VARCHAR(100),
    updated_by_name  VARCHAR(100),
    created_at       TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT uq_node_exporter_mappings_node UNIQUE (node_id)
);

