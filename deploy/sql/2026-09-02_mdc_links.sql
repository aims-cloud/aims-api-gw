-- MDC 링크 원장 — MDC 두 곳 사이의 연결 품질(지연·대역폭·손실·상태) (feat/mdc-links, 단계 4-①)
-- 배치 엔진이 "데이터 MDC 와 노드 MDC 사이가 얼마나 좋은가"를 읽을 표. 이 PR 에서는 저장·조회만 한다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 덮어써 Hibernate 가 자동 생성한다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남기고, 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -f 2026-09-02_mdc_links.sql
--
-- 쌍은 방향이 없다. 두 식별자를 사전순으로 정렬해 작은 쪽을 mdc_a 에 둔다(코드 MdcLink.Pair.of 가 보장).
-- 유니크 제약은 정렬된 쌍에 걸리므로 역방향 등록이 중복으로 잡힌다.

CREATE TABLE IF NOT EXISTS mdc_links (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mdc_a                VARCHAR(50)      NOT NULL,   -- 사전순으로 작은 MDC 식별자 (노드 라벨 mdc_id 와 같은 값)
    mdc_b                VARCHAR(50)      NOT NULL,   -- 사전순으로 큰 MDC 식별자
    latency_ms           DOUBLE PRECISION NOT NULL,   -- 왕복 지연(ms), 0 이상
    bandwidth_mbps       DOUBLE PRECISION,            -- 모르면 NULL, 있으면 0 초과
    packet_loss_percent  DOUBLE PRECISION,            -- 모르면 NULL, 있으면 0~100
    status               VARCHAR(20)      NOT NULL,   -- UP | DEGRADED | DOWN
    source               VARCHAR(20)      NOT NULL,   -- MANUAL | PROBE (PROBE 는 예약)
    description          VARCHAR(300),

    created_by           VARCHAR(100),
    created_by_name      VARCHAR(100),
    updated_by           VARCHAR(100),
    updated_by_name      VARCHAR(100),
    created_at           TIMESTAMPTZ,
    updated_at           TIMESTAMPTZ,

    CONSTRAINT uq_mdc_links_pair UNIQUE (mdc_a, mdc_b)
);

-- 한 MDC 가 걸린 링크 조회(어느 편이든)
CREATE INDEX IF NOT EXISTS idx_mdc_links_mdc_a ON mdc_links (mdc_a);
CREATE INDEX IF NOT EXISTS idx_mdc_links_mdc_b ON mdc_links (mdc_b);

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 제약을 만든다.
-- 자동 생성되지 않은 환경을 위해 같은 제약을 명시한다.
-- ※ 값을 추가할 때는 DROP 후 새 값 목록으로 다시 만들어야 한다
--   (ddl-auto=update 는 기존 CHECK 제약을 수정하지 않는다)
ALTER TABLE mdc_links DROP CONSTRAINT IF EXISTS mdc_links_status_check;
ALTER TABLE mdc_links ADD CONSTRAINT mdc_links_status_check
    CHECK (status IN ('UP', 'DEGRADED', 'DOWN'));

ALTER TABLE mdc_links DROP CONSTRAINT IF EXISTS mdc_links_source_check;
ALTER TABLE mdc_links ADD CONSTRAINT mdc_links_source_check
    CHECK (source IN ('MANUAL', 'PROBE'));

