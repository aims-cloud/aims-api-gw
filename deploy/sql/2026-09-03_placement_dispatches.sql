-- 디스패치 기록 — 배치 결정을 실행 계층으로 넘긴 요청과 그 결과 (feat/placement-dispatch, 단계 18)
-- 스케줄러는 판단 계층이고 실제 배치는 실행 계층(1세부 API)이 한다. 이 표는 그 사이의 왕복을 남긴다.
-- 실행 API 는 아직 없어 기본 모드(record)는 외부를 부르지 않고 기록만 한다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 덮어써 Hibernate 가 자동 생성한다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남기고, 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -f 2026-09-03_placement_dispatches.sql
--
-- 워크로드와는 FK 없이 식별자로만 연결한다(워크로드 삭제 시 서비스가 함께 지운다).

CREATE TABLE IF NOT EXISTS placement_dispatches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id      BIGINT       NOT NULL,       -- 논리 참조 (FK 없음)
    workload_name    VARCHAR(100),
    schedule_run_id  BIGINT,                      -- 스케줄 실행에서 나온 결정이면 실행 id, 단건 API 면 NULL
    mdc_id           VARCHAR(50),
    node_id          VARCHAR(100),
    status           VARCHAR(20)  NOT NULL,       -- 아래 CHECK 참조
    idempotency_key  VARCHAR(100) NOT NULL,       -- workloadId:scheduledAt(ms) — 같은 결정은 한 번만
    external_ref     VARCHAR(200),                -- 실행 계층이 돌려준 식별자 (record 모드는 NULL)
    message          VARCHAR(500),
    requested_at     TIMESTAMPTZ  NOT NULL,
    responded_at     TIMESTAMPTZ,
    created_by       VARCHAR(100),                -- 단건 API 는 호출자 이메일, 스케줄 실행은 SYSTEM

    CONSTRAINT uq_placement_dispatches_key UNIQUE (idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_placement_dispatches_workload ON placement_dispatches (workload_id);
CREATE INDEX IF NOT EXISTS idx_placement_dispatches_status   ON placement_dispatches (status);

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 제약을 만든다. 값을 추가할 때는 DROP 후 다시 만든다
-- (ddl-auto=update 는 기존 CHECK 를 수정하지 않는다).
--   REQUESTED → ACCEPTED → RUNNING → COMPLETED / FAILED
--   REJECTED · UNAVAILABLE : 실행 계층이 거부·불가 (워크로드 FAILED + 배정 해제)
--   TIMED_OUT              : 원격 모드 응답 시간 상한 초과 (판정하는 코드가 아직 없음 — record 모드에서는 도달하지 않음)
ALTER TABLE placement_dispatches DROP CONSTRAINT IF EXISTS placement_dispatches_status_check;
ALTER TABLE placement_dispatches ADD CONSTRAINT placement_dispatches_status_check
    CHECK (status IN ('REQUESTED', 'ACCEPTED', 'RUNNING', 'COMPLETED', 'FAILED', 'REJECTED', 'UNAVAILABLE', 'TIMED_OUT'));

