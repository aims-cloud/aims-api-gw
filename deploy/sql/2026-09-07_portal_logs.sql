-- 포털 로그 테이블 (feat/log)
-- 포털에서 일어난 일(사용자 조작·인증·인프라 작업·알람 이벤트·시스템 동작)을 한 테이블에 모으고 type 으로 구분한다
-- (docs/08 포털 로그 설계 §3.1). 관측 > 로그 관리 화면이 조회한다.
-- 알람 원장(alarm_histories)·작업은 ref_type/ref_id 로 약하게 참조하며 FK 를 걸지 않는다.
-- VM PostgreSQL은 ddl-auto: validate 이므로 배포 전 수동 실행 필요:
--   psql -U aims -d aims -f 2026-09-07_portal_logs.sql

CREATE TABLE IF NOT EXISTS portal_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(16)  NOT NULL,                 -- AUTH | AUDIT | ACTION | ALARM | SYSTEM | ACCESS
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL,     -- 요청 진입 / 이벤트 시각 (화면 "생성 일시")
    completed_at TIMESTAMP WITH TIME ZONE,              -- 응답 반환 / 작업 완료 시각 (IN_PROGRESS 면 NULL)
    user_id      VARCHAR(64),                           -- 시스템 이벤트는 NULL
    user_name    VARCHAR(100),                          -- 기록 시점 표시명 스냅샷
    client_ip    VARCHAR(45),
    screen       VARCHAR(50),                           -- 화면 표시명, 없으면 NULL ("-")
    action       VARCHAR(30),
    content      VARCHAR(500) NOT NULL,
    result       VARCHAR(16)  NOT NULL,                 -- SUCCESS | FAILURE | IN_PROGRESS
    description  VARCHAR(1000),                         -- 실패 사유, 부가 설명
    ref_type     VARCHAR(30),                           -- ALARM_HISTORY, INFRA_JOB ...
    ref_id       VARCHAR(100),
    request_id   VARCHAR(64),                           -- MDC requestId (서버 로그 대조용)
    http_method  VARCHAR(8),
    request_uri  VARCHAR(300),                          -- 쿼리 스트링 제외
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 목록 기본 정렬 (started_at desc)
CREATE INDEX IF NOT EXISTS idx_portal_logs_started_at      ON portal_logs (started_at);
-- 타입 필터 + 기간
CREATE INDEX IF NOT EXISTS idx_portal_logs_type_started_at ON portal_logs (type, started_at);
-- 사용자별 조회
CREATE INDEX IF NOT EXISTS idx_portal_logs_user_started_at ON portal_logs (user_id, started_at);
-- ACTION 완료 갱신 / 알람 원장 역참조
CREATE INDEX IF NOT EXISTS idx_portal_logs_ref             ON portal_logs (ref_type, ref_id);
