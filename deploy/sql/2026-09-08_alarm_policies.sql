-- 알람 정책 원장 (feat/event-alarm) — docs/09 알람 설계 A.5.3 · A.6 · C.2
-- 정책(alarm_policies) + 개별 대상 자원(alarm_policy_targets) + 수신자(alarm_policy_recipients).
-- 기존 alarm_rules 는 이 원장으로 대체됐고 코드에서 제거됐다(엔티티가 없으므로 validate 에 걸리지 않음).
-- 운영 행이 있으면 아래 SELECT 로 확인해 정책으로 옮긴 뒤 마지막 DROP 을 실행한다(행이 없으면 바로 DROP).
--   SELECT id, name, metric_name, condition, threshold, severity, notify_channel, enabled FROM alarm_rules;
-- VM PostgreSQL은 ddl-auto: validate 이므로 새 백엔드 기동 전 수동 실행 필요:
--   sudo -u postgres psql -d aims -v ON_ERROR_STOP=1 -f 2026-09-08_alarm_policies.sql
--   sudo -u postgres psql -d aims -c "ALTER TABLE alarm_policies OWNER TO aims; ALTER TABLE alarm_policy_targets OWNER TO aims; ALTER TABLE alarm_policy_recipients OWNER TO aims;"

CREATE TABLE IF NOT EXISTS alarm_policies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(16)  NOT NULL DEFAULT 'METRIC',   -- METRIC | LOG(1차 제외)
    name             VARCHAR(100) NOT NULL,
    role_name        VARCHAR(50)  NOT NULL,                    -- 적용 범위: 역할 (필수)
    area_id          VARCHAR(120),                             -- 적용 범위: 자원 영역 (mdcId 또는 TB:{nsId}, NULL = 역할 전체)
    area_kind        VARCHAR(16),                              -- MDC | NAMESPACE
    resource_type    VARCHAR(20)  NOT NULL,                    -- node | vm | gpu
    target_scope     VARCHAR(16)  NOT NULL,                    -- ALL | INDIVIDUAL
    metric           VARCHAR(40)  NOT NULL,                    -- AlarmMetric 코드 (예: CPU_USED_PERCENT)
    operator         VARCHAR(8)   NOT NULL,                    -- GT | GTE | LT | LTE | EQ
    threshold        DOUBLE PRECISION NOT NULL,
    level            VARCHAR(16)  NOT NULL,                    -- INFO | WARNING | CRITICAL
    duration_seconds INTEGER      NOT NULL DEFAULT 0,          -- 조건 지속 시간 (0 = 즉시)
    channels         VARCHAR(64)  NOT NULL,                    -- EMAIL,SMS (CSV)
    description      VARCHAR(1000),
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by       VARCHAR(100),                             -- 생성자 이메일 (포털 로그 userId 와 같은 체계)
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_alarm_policies_role         ON alarm_policies (role_name);
CREATE INDEX IF NOT EXISTS idx_alarm_policies_enabled_type ON alarm_policies (enabled, type);

-- 개별 대상 자원 (target_scope = INDIVIDUAL). resource_id 는 assets.id 또는 TB:{ns}/{infra}/{node}
CREATE TABLE IF NOT EXISTS alarm_policy_targets (
    policy_id    BIGINT       NOT NULL REFERENCES alarm_policies (id) ON DELETE CASCADE,
    resource_id  VARCHAR(200) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alarm_policy_targets_policy   ON alarm_policy_targets (policy_id);
CREATE INDEX IF NOT EXISTS idx_alarm_policy_targets_resource ON alarm_policy_targets (resource_id);

-- 수신자. INDIVIDUAL 은 users.id, ORGANIZATION 은 users.organization 문자열(조직 원장 확정 전)
CREATE TABLE IF NOT EXISTS alarm_policy_recipients (
    policy_id    BIGINT       NOT NULL REFERENCES alarm_policies (id) ON DELETE CASCADE,
    target_type  VARCHAR(16)  NOT NULL,                        -- INDIVIDUAL | ORGANIZATION
    target_id    VARCHAR(100) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alarm_policy_recipients_policy ON alarm_policy_recipients (policy_id);

-- 구 규칙 원장 제거 (위 SELECT 로 이관 여부 확인 후 실행)
DROP TABLE IF EXISTS alarm_rules;
