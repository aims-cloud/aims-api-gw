-- 노드 전력 사양 원장 — 노드별 정격 전력(W) (feat/node-power-spec, 단계 20)
-- IPMI 는 "지금 쓰는 전력"만 알려 주고 정격은 알려 주지 않는다. 그래서 지금까지 모든 노드를 설정 기본값(500W)
-- 하나로 봤고, 그 값이 배치 제외 판정·전력 점수·회수 가능 전력·통합 절감 추정 네 곳에 그대로 쓰였다.
-- 이 표는 운영자가 아는 값(장비 사양서)을 넣어 그 가정을 실제 값으로 바꾼다. 비어 있으면 종전과 같이 설정값을 쓴다.
--
-- ddl-auto 에 따라 실행 필요 여부가 다르다:
--   * 기본 프로파일(application.yml)은 validate — 배포 전에 이 스크립트를 먼저 실행해야 기동된다.
--   * 배포 VM 은 환경파일(SPRING_JPA_HIBERNATE_DDL_AUTO=update)로 덮어써 Hibernate 가 자동 생성한다.
--     그래도 스키마를 의도대로 고정하기 위해 스크립트로 남기고, 배포 후 information_schema 로 대조한다.
--   psql -U aims -d aims -f 2026-09-04_node_power_specs.sql
--
-- 정격에는 크기 상한을 두지 않는다. 실데이터가 없는 지금 상한은 추측이라 정당한 장비(10kW 급 GPU 서버, 수십 kW 랙)를
-- 막을 수 있다. 서비스는 "0 보다 큰 유한한 값"만 검사한다.

CREATE TABLE IF NOT EXISTS node_power_specs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id          VARCHAR(100)     NOT NULL,   -- Prometheus instance 라벨과 같은 문자열 (예: seoul-01:9100)
    capacity_watts   DOUBLE PRECISION NOT NULL,   -- 정격 전력(W), 0 초과·유한
    source           VARCHAR(20)      NOT NULL,   -- MANUAL | SPEC_SHEET | MEASURED (MEASURED 는 예약)
    description      VARCHAR(300),

    created_by       VARCHAR(100),
    created_by_name  VARCHAR(100),
    updated_by       VARCHAR(100),
    updated_by_name  VARCHAR(100),
    created_at       TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT uq_node_power_specs_node UNIQUE (node_id)
);

-- ── 열거형 CHECK 제약 ────────────────────────────────────────
-- Hibernate 는 @Enumerated(EnumType.STRING) 컬럼에 CHECK 제약을 만든다. 값을 추가할 때는 DROP 후 다시 만든다
-- (ddl-auto=update 는 기존 CHECK 를 수정하지 않는다).
ALTER TABLE node_power_specs DROP CONSTRAINT IF EXISTS node_power_specs_source_check;
ALTER TABLE node_power_specs ADD CONSTRAINT node_power_specs_source_check
    CHECK (source IN ('MANUAL', 'SPEC_SHEET', 'MEASURED'));

